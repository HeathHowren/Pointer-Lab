template <typename T>
using Result = infra::Result<T>;

std::string escapeForCpp(const std::string& text) {
    std::string out;
    for (const char c : text) {
        if (c == '\\' || c == '"') {
            out.push_back('\\');
            out.push_back(c);
        } else if (c == '\n' || c == '\r' || c == '\t') {
            out.push_back(' ');
        } else {
            out.push_back(c);
        }
    }
    return out;
}

std::string byteArray(const std::vector<std::uint8_t>& bytes) {
    std::ostringstream out;
    for (std::size_t i = 0; i < bytes.size(); ++i) {
        if (i > 0) {
            out << ", ";
        }
        out << "0x" << std::hex << std::uppercase;
        if (bytes[i] < 0x10) {
            out << '0';
        }
        out << static_cast<unsigned>(bytes[i]) << std::dec << std::nouppercase;
    }
    return out.str();
}

// F1..F12 as a virtual key code, or 0 for anything else. The trainer only
// supports the function keys because that is what the address list registers,
// and inventing a wider mapping here would generate hotkeys the table cannot
// express.
int virtualKey(const std::string& hotkey) {
    if (hotkey.size() < 2 || (hotkey[0] != 'F' && hotkey[0] != 'f')) {
        return 0;
    }
    const auto number = std::atoi(hotkey.c_str() + 1);
    if (number < 1 || number > 12) {
        return 0;
    }
    return 0x70 + (number - 1); // VK_F1
}

